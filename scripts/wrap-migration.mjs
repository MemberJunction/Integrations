#!/usr/bin/env node
/**
 * After `mj sync push --dir metadata` captures the seed SQL into a connector's migrations/ (raw,
 * literal __mj), this standardizes the newest unnamed .sql into the Flyway convention:
 *
 *   migrations/V<YYYYMMDDHHMM>__<slug>__Metadata.sql   (+ a header comment)
 *
 * Usage:  node scripts/wrap-migration.mjs <Category>/<Connector>
 *   e.g.  node scripts/wrap-migration.mjs CRM/HubSpot
 *
 * Idempotent: files already matching V<digits>__… are left alone. Run `build-pg-migrations.mjs` after.
 */
import { readFileSync, writeFileSync, readdirSync, renameSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const rel = process.argv[2];
if (!rel) { console.error('Usage: node scripts/wrap-migration.mjs <Category>/<Connector>'); process.exit(1); }

const appDir = join(ROOT, rel);
const migDir = join(appDir, 'migrations');
const manifest = JSON.parse(readFileSync(join(appDir, 'mj-app.json'), 'utf-8'));
const slug = manifest.name.replace(/^connector-/, '');

const flywayNamed = /^[BV]\d{12}__/;
const raw = readdirSync(migDir).filter((f) => f.endsWith('.sql') && !flywayNamed.test(f));
if (raw.length === 0) { console.log(`No unnamed .sql in ${rel}/migrations — nothing to wrap (run \`mj sync push --dir metadata\` first).`); process.exit(0); }

// Build a monotonic V-timestamp newer than any existing migration in this connector.
const existing = readdirSync(migDir).map((f) => f.match(/^[BV](\d{12})__/)).filter(Boolean).map((m) => Number(m[1]));
const now = new Date();
const stampNow = `${now.getFullYear()}${String(now.getMonth() + 1).padStart(2, '0')}${String(now.getDate()).padStart(2, '0')}${String(now.getHours()).padStart(2, '0')}${String(now.getMinutes()).padStart(2, '0')}`;
let stamp = Math.max(Number(stampNow), existing.length ? Math.max(...existing) + 1 : 0);

for (const file of raw.sort()) {
  const src = readFileSync(join(migDir, file), 'utf-8');
  const header = `-- ${manifest.displayName} — connector metadata seed (generated by \`mj sync push\`)\n` +
    `-- Seeds the core __mj integration catalog (Integration / IntegrationObject / IntegrationObjectField + Actions).\n` +
    `-- Do not hand-edit; regenerate from ../metadata via \`mj sync push\` + \`scripts/wrap-migration.mjs\`.\n\n`;
  const target = `V${stamp}__${slug}__Metadata.sql`;
  writeFileSync(join(migDir, file), header + src);
  renameSync(join(migDir, file), join(migDir, target));
  console.log(`✓ ${rel}/migrations/${target}`);
  stamp++;
}
console.log(`Next: node scripts/build-pg-migrations.mjs ${rel}`);
