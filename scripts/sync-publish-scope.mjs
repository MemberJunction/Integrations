#!/usr/bin/env node
/**
 * Regenerates scripts/connector-publish-scope.json from the connectors' package.json `private` flags.
 *
 * The scope file decides which connectors build-seed-migrations.mjs regenerates by default. It used to
 * be maintained by hand alongside the `private` flags, which are what the catalog build actually reads —
 * two sources of truth for one fact, and they drifted (four published connectors sat in `hold`; fourteen
 * published connectors were in neither list, so their seed migrations were silently never regenerated).
 * Now the flags are the fact and this script projects them. validate-invariants.mjs fails CI if the
 * checked-in file disagrees with what this would produce.
 *
 * Usage: node scripts/sync-publish-scope.mjs [--check]
 */
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const SCOPE_PATH = join(REPO_ROOT, 'scripts', 'connector-publish-scope.json');
const COMMENT =
  'Which connector Open Apps get their seed migrations regenerated by scripts/build-seed-migrations.mjs. ' +
  'This file is NOT an independent source of truth: `hold` is exactly the set of connector directories whose ' +
  'package.json sets "private": true, and `publish` is exactly the rest. Together they must cover every directory ' +
  'that has an mj-app.json, and nothing else. scripts/validate-invariants.mjs enforces all three of those statements ' +
  'in CI, so this file cannot drift from the private flags the way it did before. To move a connector between the ' +
  'lists, flip "private" in its package.json and re-run `node scripts/sync-publish-scope.mjs`. Platform/FileFeed, ' +
  'Platform/RelationalDB and Shared/SchemaMerge appear in neither list on purpose: they are libraries, not Open Apps, ' +
  'and have no mj-app.json.';

/** Every connector Open App directory, repo-relative, sorted. */
function openAppDirs(dir = REPO_ROOT, out = []) {
  for (const entry of readdirSync(dir)) {
    if (['node_modules', 'dist', '.git', '.turbo', 'scripts', '.changeset', '.github'].includes(entry)) continue;
    const p = join(dir, entry);
    if (!statSync(p).isDirectory()) continue;
    if (existsSync(join(p, 'mj-app.json')) && existsSync(join(p, 'package.json'))) out.push(p.slice(REPO_ROOT.length + 1));
    else openAppDirs(p, out);
  }
  return out.sort();
}

const isPrivate = (rel) => JSON.parse(readFileSync(join(REPO_ROOT, rel, 'package.json'), 'utf-8')).private === true;
const dirs = openAppDirs();
const next = JSON.stringify(
  { _comment: COMMENT, publish: dirs.filter((d) => !isPrivate(d)), hold: dirs.filter(isPrivate) },
  null,
  2
) + '\n';

if (process.argv.includes('--check')) {
  if (readFileSync(SCOPE_PATH, 'utf-8') !== next) {
    console.error('✗ connector-publish-scope.json is stale — run `node scripts/sync-publish-scope.mjs`.');
    process.exit(1);
  }
  console.log('✓ connector-publish-scope.json matches the package.json private flags.');
} else {
  writeFileSync(SCOPE_PATH, next);
  console.log(`✓ connector-publish-scope.json written: ${dirs.length} Open Apps (${dirs.filter((d) => !isPrivate(d)).length} publish, ${dirs.filter(isPrivate).length} hold).`);
}
